-- Monthly Dori Pass: Rocky Points currency, per-user randomized daily missions,
-- progressive 100-node map rewards, weekly challenges and seasonal collectibles.
-- All points, coin grants and cosmetic ownership are server-controlled.

create table if not exists public.dori_pass_rocky_point_wallets (
  user_id uuid primary key references auth.users(id) on delete cascade,
  balance bigint not null default 0 check (balance >= 0),
  updated_at timestamptz not null default now()
);
create table if not exists public.dori_pass_rocky_point_transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  season_key text not null check (season_key ~ '^[0-9]{4}-[0-9]{2}$'),
  transaction_type text not null check (transaction_type in ('daily_mission','weekly_challenge')),
  source_key text not null,
  amount integer not null check (amount > 0),
  mission_date date not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (user_id, transaction_type, source_key)
);
create table if not exists public.dori_pass_daily_missions (
  user_id uuid not null references auth.users(id) on delete cascade,
  mission_date date not null,
  slot integer not null check (slot between 1 and 5),
  mission_key text not null,
  title text not null,
  description text not null,
  target integer not null check (target > 0),
  reward_points integer not null check (reward_points > 0),
  progress integer not null default 0 check (progress >= 0),
  completed_at timestamptz,
  claimed_at timestamptz,
  created_at timestamptz not null default now(),
  primary key (user_id,mission_date,slot),
  unique (user_id,mission_date,mission_key)
);
create index if not exists dori_pass_points_season_user_idx
  on public.dori_pass_rocky_point_transactions(user_id,season_key,created_at);
create index if not exists dori_pass_daily_missions_user_date_idx
  on public.dori_pass_daily_missions(user_id,mission_date,claimed_at);

alter table public.dori_pass_challenge_claims
  add column if not exists rocky_points_reward integer not null default 0;
update public.dori_pass_challenge_claims
set rocky_points_reward=xp_reward
where rocky_points_reward=0 and xp_reward>0;

alter table public.dori_pass_rocky_point_wallets enable row level security;
alter table public.dori_pass_rocky_point_transactions enable row level security;
alter table public.dori_pass_daily_missions enable row level security;
drop policy if exists dori_pass_points_wallet_select_own on public.dori_pass_rocky_point_wallets;
create policy dori_pass_points_wallet_select_own on public.dori_pass_rocky_point_wallets
  for select to authenticated using (user_id=(select auth.uid()));
drop policy if exists dori_pass_points_transactions_select_own on public.dori_pass_rocky_point_transactions;
create policy dori_pass_points_transactions_select_own on public.dori_pass_rocky_point_transactions
  for select to authenticated using (user_id=(select auth.uid()));
drop policy if exists dori_pass_daily_missions_select_own on public.dori_pass_daily_missions;
create policy dori_pass_daily_missions_select_own on public.dori_pass_daily_missions
  for select to authenticated using (user_id=(select auth.uid()));
revoke all on public.dori_pass_rocky_point_wallets from anon,authenticated;
revoke all on public.dori_pass_rocky_point_transactions from anon,authenticated;
revoke all on public.dori_pass_daily_missions from anon,authenticated;
grant select on public.dori_pass_rocky_point_wallets to authenticated;
grant select on public.dori_pass_rocky_point_transactions to authenticated;
grant select on public.dori_pass_daily_missions to authenticated;

drop trigger if exists trg_dori_pass_daily_mission on public.user_daily_missions;
drop trigger if exists trg_dori_pass_attendance on public.user_attendance_days;
drop trigger if exists trg_dori_pass_random_box on public.dori_box_history;
drop trigger if exists trg_dori_pass_chess on public.chess_games;
drop trigger if exists trg_dori_pass_study_focus on public.rockey_study_focus_sessions;
