CREATE OR REPLACE FUNCTION public.dori_pass_sync_title_selection(p_title text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_uid uuid := auth.uid();
  v_owned public.dori_pass_cosmetics%rowtype;
  v_equipped jsonb;
  v_existing jsonb;
  v_has_owned boolean := false;
begin
  if v_uid is null then raise exception '로그인이 필요합니다.'; end if;
  if not exists(select 1 from public.users where user_id=v_uid::text and equipped_title is not distinct from p_title) then
    return jsonb_build_object('ok',false,'reason','title_state_mismatch');
  end if;

  update public.dori_pass_cosmetics set is_equipped=false
  where user_id=v_uid and kind='title' and is_equipped;

  select * into v_owned
  from public.dori_pass_cosmetics
  where user_id=v_uid and kind='title' and display_name is not distinct from p_title
  order by claimed_at desc limit 1;
  v_has_owned := found;

  select coalesce(customization->'dori_pass_equipped','{}'::jsonb)
  into v_existing from public.user_customization where user_id=v_uid;
  v_equipped := (case when jsonb_typeof(v_existing)='object' then v_existing else '{}'::jsonb end) - 'title';

  if v_has_owned and v_owned.cosmetic_key is not null then
    update public.dori_pass_cosmetics set is_equipped=true
    where user_id=v_uid and cosmetic_key=v_owned.cosmetic_key;
    v_equipped := v_equipped || jsonb_build_object('title', jsonb_build_object(
      'key',v_owned.cosmetic_key,'name',v_owned.display_name,'kind','title',
      'icon',v_owned.icon,'rarity',v_owned.rarity,'season_key',v_owned.season_key,'tier',v_owned.tier
    ));
  end if;

  insert into public.user_customization(user_id,customization,updated_at)
  values(v_uid,jsonb_build_object('dori_pass_equipped',v_equipped),now())
  on conflict(user_id) do update
  set customization=coalesce(public.user_customization.customization,'{}'::jsonb)
        || jsonb_build_object('dori_pass_equipped',v_equipped),
      updated_at=now();

  return jsonb_build_object('ok',true,'pass_title_equipped',v_has_owned);
end
$function$;

