CREATE OR REPLACE FUNCTION public.dori_pass_equip_cosmetic(p_cosmetic_key text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_uid uuid := auth.uid();
  v_item public.dori_pass_cosmetics%rowtype;
  v_info jsonb;
begin
  if v_uid is null then raise exception '로그인이 필요합니다.'; end if;
  select * into v_item from public.dori_pass_cosmetics
  where user_id=v_uid and cosmetic_key=p_cosmetic_key;
  if not found then return jsonb_build_object('ok',false,'reason','not_owned'); end if;

  update public.dori_pass_cosmetics set is_equipped=false
  where user_id=v_uid and kind=v_item.kind and is_equipped;
  update public.dori_pass_cosmetics set is_equipped=true
  where user_id=v_uid and cosmetic_key=p_cosmetic_key;

  v_info := jsonb_build_object(
    'key',v_item.cosmetic_key,'name',v_item.display_name,'kind',v_item.kind,
    'icon',v_item.icon,'rarity',v_item.rarity,'season_key',v_item.season_key,'tier',v_item.tier
  );

  if v_item.kind = 'title' then
    update public.users set equipped_title = v_item.display_name
    where user_id = v_uid::text;
    if not found then raise exception '사용자 계정 정보를 찾을 수 없습니다.'; end if;
  end if;

  insert into public.user_customization(user_id,customization,updated_at)
  values (
    v_uid,
    jsonb_build_object('dori_pass_equipped',jsonb_build_object(v_item.kind,v_info)),
    now()
  )
  on conflict (user_id) do update
  set customization = coalesce(public.user_customization.customization,'{}'::jsonb)
    || jsonb_build_object(
       'dori_pass_equipped',
       coalesce(public.user_customization.customization->'dori_pass_equipped','{}'::jsonb)
       || jsonb_build_object(v_item.kind,v_info)
    ),
    updated_at = now();

  return jsonb_build_object('ok',true,'equipped',v_info);
end
$function$;

CREATE OR REPLACE FUNCTION public.dori_pass_get_dashboard()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_uid uuid := auth.uid();
  v_today date := timezone('Asia/Seoul', now())::date;
  v_season_key text;
  v_start date;
  v_end date;
  v_week_start date;
  v_xp integer := 0;
  v_tier integer := 0;
  v_next_xp integer := 0;
  v_challenges jsonb := '[]'::jsonb;
  v_tiers jsonb := '[]'::jsonb;
  v_achievements jsonb := '[]'::jsonb;
  v_cosmetics jsonb := '[]'::jsonb;
  v_claimed_challenges integer := 0;
  v_domain_count integer := 0;
  v_user_name text;
begin
  if v_uid is null then raise exception '로그인 후 돌이 패스를 이용할 수 있습니다.'; end if;

  v_season_key := to_char(v_today, 'YYYY-MM');
  v_start := date_trunc('month', v_today::timestamp)::date;
  v_end := (v_start + interval '1 month')::date;
  v_week_start := date_trunc('week', v_today::timestamp)::date;

  select coalesce(sum(xp), 0)::integer into v_xp
  from public.dori_pass_event_ledger
  where user_id = v_uid and season_key = v_season_key;
  v_tier := least(100, floor(v_xp::numeric / 100)::integer);
  if v_tier < 100 then v_next_xp := greatest(0, ((v_tier + 1) * 100) - v_xp); end if;

  select name into v_user_name from public.users where user_id = v_uid::text limit 1;

  select coalesce(jsonb_agg(
    public.dori_pass_tier_reward(v_season_key, g.tier)
      || jsonb_build_object('claimed', c.tier is not null, 'unlocked', g.tier <= v_tier)
    order by g.tier
  ), '[]'::jsonb)
  into v_tiers
  from generate_series(1, 100) as g(tier)
  left join public.dori_pass_tier_claims c
    on c.user_id = v_uid and c.season_key = v_season_key and c.tier = g.tier;

  select coalesce(jsonb_agg(
    jsonb_build_object(
      'key', q.challenge_key,
      'title', q.title,
      'description', q.description,
      'event_type', q.event_type,
      'target', q.target_count,
      'progress', least(q.target_count, q.current_count),
      'raw_progress', q.current_count,
      'xp_reward', q.xp_reward,
      'claimed', q.is_claimed,
      'claimable', (q.current_count >= q.target_count and not q.is_claimed)
    ) order by q.sort_order
  ), '[]'::jsonb)
  into v_challenges
  from (
    select defs.*,
      (select count(*)::integer from public.dori_pass_event_ledger e
       where e.user_id = v_uid and e.season_key = v_season_key
         and e.event_type = defs.event_type
         and e.event_date between v_week_start and v_today) as current_count,
      exists (select 1 from public.dori_pass_challenge_claims cc
       where cc.user_id = v_uid and cc.season_key = v_season_key
         and cc.week_start = v_week_start and cc.challenge_key = defs.challenge_key) as is_claimed
    from (values
      ('show_up', '꾸준한 발걸음', '이번 주 출석 기록 5일을 쌓으세요.', 'attendance', 5, 200, 1),
