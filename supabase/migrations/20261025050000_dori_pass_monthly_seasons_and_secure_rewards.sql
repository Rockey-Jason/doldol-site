CREATE OR REPLACE FUNCTION public.dori_pass_record_event(p_user_id uuid, p_event_type text, p_source_id text, p_requested_xp integer, p_occurred_at timestamp with time zone, p_payload jsonb DEFAULT '{}'::jsonb)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_occurred_at timestamptz := coalesce(p_occurred_at, now());
  v_event_date date;
  v_season_key text;
  v_event_cap integer;
  v_daily_cap integer;
  v_count_cap integer;
  v_count integer;
  v_daily_xp integer;
  v_xp integer;
  v_inserted integer;
begin
  if p_user_id is null or p_source_id is null or length(btrim(p_source_id)) = 0
     or length(p_source_id) > 200 or p_requested_xp is null or p_requested_xp <= 0
     or v_occurred_at > now() + interval '10 minutes' then
    return false;
  end if;

  case p_event_type
    when 'daily_mission' then v_event_cap := 8;  v_daily_cap := 40; v_count_cap := 5;
    when 'attendance'    then v_event_cap := 5;  v_daily_cap := 5;  v_count_cap := 1;
    when 'random_box'    then v_event_cap := 3;  v_daily_cap := 30; v_count_cap := 10;
    when 'chess_game'    then v_event_cap := 15; v_daily_cap := 45; v_count_cap := 3;
    when 'study_focus'   then v_event_cap := 20; v_daily_cap := 50; v_count_cap := 4;
    when 'stock_trade'   then v_event_cap := 4;  v_daily_cap := 20; v_count_cap := 5;
    when 'bank_transaction' then v_event_cap := 2; v_daily_cap := 10; v_count_cap := 5;
    when 'news_read'     then v_event_cap := 10; v_daily_cap := 50; v_count_cap := 5;
    when 'weekly_challenge' then v_event_cap := 300; v_daily_cap := 1500; v_count_cap := 6;
    else return false;
  end case;

  v_event_date := timezone('Asia/Seoul', v_occurred_at)::date;
  v_season_key := to_char(v_event_date, 'YYYY-MM');
  perform pg_advisory_xact_lock(hashtextextended(p_user_id::text || '|' || v_event_date::text || '|' || p_event_type, 0));

  select count(*)::integer, coalesce(sum(xp), 0)::integer
    into v_count, v_daily_xp
  from public.dori_pass_event_ledger
  where user_id = p_user_id
    and event_type = p_event_type
    and event_date = v_event_date;

  if v_count >= v_count_cap then return false; end if;
  v_xp := least(v_event_cap, p_requested_xp, greatest(0, v_daily_cap - v_daily_xp));
  if v_xp <= 0 then return false; end if;

  insert into public.dori_pass_event_ledger
    (user_id, season_key, event_type, source_id, event_date, xp, payload, created_at)
  values
    (p_user_id, v_season_key, p_event_type, p_source_id, v_event_date, v_xp,
     coalesce(p_payload, '{}'::jsonb), now())
  on conflict (user_id, season_key, event_type, source_id) do nothing;

  get diagnostics v_inserted = row_count;
  return v_inserted > 0;
end
$function$;

