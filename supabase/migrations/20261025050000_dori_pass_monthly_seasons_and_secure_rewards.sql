CREATE OR REPLACE FUNCTION public.dori_pass_news_read_trigger()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_uid uuid;
  v_value text;
  v_news_number bigint;
begin
  if new.user_id !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then return new; end if;
  v_uid := new.user_id::uuid;
  for v_value in
    select jsonb_array_elements_text(coalesce(new.read_dori_news_numbers, '[]'::jsonb))
  loop
    if not exists (
      select 1 from jsonb_array_elements_text(coalesce(old.read_dori_news_numbers, '[]'::jsonb)) old_value
      where old_value = v_value
    ) then
      begin
        v_news_number := v_value::bigint;
        if exists (select 1 from public.rockey_news where news_number = v_news_number) then
          perform public.dori_pass_record_event(
            v_uid, 'news_read', v_news_number::text, 10, now(),
            jsonb_build_object('news_number', v_news_number)
          );
        end if;
      exception when invalid_text_representation or numeric_value_out_of_range then
        continue;
      end;
    end if;
  end loop;
  return new;
end
$function$;

