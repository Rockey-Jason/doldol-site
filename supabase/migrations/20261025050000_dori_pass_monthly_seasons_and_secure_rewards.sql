-- Dori Pass monthly-season system.
-- Re-runnable schema/function snapshot for local setup; activity backfill is
-- idempotent because ledger events use a unique per-user source key.
create table if not exists public.dori_pass_event_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  season_key text not null check (season_key ~ '^[0-9]{4}-[0-9]{2}$'),
  event_type text not null, source_id text not null, event_date date not null,
  xp integer not null check (xp > 0), payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (user_id, season_key, event_type, source_id)
);
create table if not exists public.dori_pass_tier_claims (
  user_id uuid not null references auth.users(id) on delete cascade,
  season_key text not null check (season_key ~ '^[0-9]{4}-[0-9]{2}$'),
  tier integer not null check (tier between 1 and 100),
  coin_reward bigint not null check (coin_reward >= 0),
  claimed_at timestamptz not null default now(),
  primary key (user_id, season_key, tier)
);
create table if not exists public.dori_pass_challenge_claims (
  user_id uuid not null references auth.users(id) on delete cascade,
  season_key text not null check (season_key ~ '^[0-9]{4}-[0-9]{2}$'),
  week_start date not null, challenge_key text not null,
  xp_reward integer not null check (xp_reward > 0),
  claimed_at timestamptz not null default now(),
  primary key (user_id, season_key, week_start, challenge_key)
);
create table if not exists public.dori_pass_achievement_claims (
  user_id uuid not null references auth.users(id) on delete cascade,
  season_key text not null check (season_key ~ '^[0-9]{4}-[0-9]{2}$'),
  achievement_key text not null, coin_reward bigint not null check (coin_reward >= 0),
  claimed_at timestamptz not null default now(),
  primary key (user_id, season_key, achievement_key)
);
create table if not exists public.dori_pass_cosmetics (
  user_id uuid not null references auth.users(id) on delete cascade,
  season_key text not null check (season_key ~ '^[0-9]{4}-[0-9]{2}$'),
  tier integer not null check (tier between 1 and 100),
  cosmetic_key text not null,
  kind text not null check (kind in ('title','profile_frame','special_icon')),
  display_name text not null,
  rarity text not null check (rarity in ('Rare','Epic','Legendary','Myth','Doronum')),
  icon text not null default '✦', is_equipped boolean not null default false,
  claimed_at timestamptz not null default now(),
  primary key (user_id, cosmetic_key)
);
create index if not exists dori_pass_event_season_user_idx
  on public.dori_pass_event_ledger (user_id, season_key, event_date);
create index if not exists dori_pass_event_weekly_idx
  on public.dori_pass_event_ledger (user_id, season_key, event_type, event_date);
create index if not exists dori_pass_cosmetics_user_idx
  on public.dori_pass_cosmetics (user_id, kind, is_equipped);
create unique index if not exists dori_pass_one_equipped_cosmetic_per_kind
  on public.dori_pass_cosmetics (user_id, kind) where is_equipped;

alter table public.dori_pass_event_ledger enable row level security;
alter table public.dori_pass_tier_claims enable row level security;
alter table public.dori_pass_challenge_claims enable row level security;
alter table public.dori_pass_achievement_claims enable row level security;
alter table public.dori_pass_cosmetics enable row level security;
drop policy if exists dori_pass_events_select_own on public.dori_pass_event_ledger;
create policy dori_pass_events_select_own on public.dori_pass_event_ledger
  for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists dori_pass_tiers_select_own on public.dori_pass_tier_claims;
create policy dori_pass_tiers_select_own on public.dori_pass_tier_claims
  for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists dori_pass_challenges_select_own on public.dori_pass_challenge_claims;
create policy dori_pass_challenges_select_own on public.dori_pass_challenge_claims
  for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists dori_pass_achievements_select_own on public.dori_pass_achievement_claims;
create policy dori_pass_achievements_select_own on public.dori_pass_achievement_claims
  for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists dori_pass_cosmetics_select_own on public.dori_pass_cosmetics;
create policy dori_pass_cosmetics_select_own on public.dori_pass_cosmetics
  for select to authenticated using (user_id = (select auth.uid()));
revoke all on public.dori_pass_event_ledger from anon, authenticated;
