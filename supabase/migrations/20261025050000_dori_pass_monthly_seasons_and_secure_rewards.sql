    order by completed_at, user_id, mission_key
  loop
    perform public.dori_pass_record_event(r.user_id,'daily_mission',r.mission_key || ':' || r.mission_date::text,8,r.completed_at,jsonb_build_object('mission_key',r.mission_key,'mission_date',r.mission_date));
  end loop;

  for r in select user_id, attendance_date from public.user_attendance_days
    where attendance_date >= date_trunc('month', timezone('Asia/Seoul', now()))::date
      and attendance_date <= timezone('Asia/Seoul', now())::date
      and user_id ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
    order by attendance_date, user_id
  loop
    perform public.dori_pass_record_event(r.user_id::uuid,'attendance',r.attendance_date::text,5,(r.attendance_date::timestamp + interval '12 hours') at time zone 'Asia/Seoul',jsonb_build_object('attendance_date',r.attendance_date));
  end loop;

  for r in select id,user_id,box_type,item_name,rarity,created_at from public.dori_box_history
    where timezone('Asia/Seoul',created_at)::date >= date_trunc('month',timezone('Asia/Seoul',now()))::date and created_at <= now()
    order by created_at,id
  loop
    perform public.dori_pass_record_event(r.user_id,'random_box',r.id::text,3,r.created_at,jsonb_build_object('box_type',r.box_type,'rarity',r.rarity,'item_name',r.item_name));
  end loop;

  for r in select id,user_id,result,mode,created_at from public.chess_games
    where result is not null and btrim(result) not in ('','*','pending','ongoing')
      and timezone('Asia/Seoul',created_at)::date >= date_trunc('month',timezone('Asia/Seoul',now()))::date and created_at <= now()
    order by created_at,id
  loop
    perform public.dori_pass_record_event(r.user_id,'chess_game',r.id::text,15,r.created_at,jsonb_build_object('result',r.result,'mode',r.mode));
  end loop;

  for r in select id,user_id,subject,actual_seconds,ended_at from public.rockey_study_focus_sessions
    where session_type='focus' and status='completed' and coalesce(actual_seconds,0)>=300 and ended_at is not null
      and timezone('Asia/Seoul',ended_at)::date >= date_trunc('month',timezone('Asia/Seoul',now()))::date and ended_at <= now()
    order by ended_at,id
  loop
    perform public.dori_pass_record_event(r.user_id,'study_focus',r.id::text,least(20,greatest(2,floor(r.actual_seconds::numeric/300)::integer*2)),r.ended_at,jsonb_build_object('actual_seconds',r.actual_seconds,'subject',r.subject));
  end loop;

  for r in select id,buyer_user_id,seller_user_id,stock_id,notional,executed_at from public.dori_stock_executions
    where timezone('Asia/Seoul',executed_at)::date >= date_trunc('month',timezone('Asia/Seoul',now()))::date and executed_at <= now()
    order by executed_at,id
  loop
    if r.buyer_user_id is not null then
      perform public.dori_pass_record_event(r.buyer_user_id,'stock_trade',r.id::text || ':buyer',4,r.executed_at,jsonb_build_object('stock_id',r.stock_id,'side','buy','notional',r.notional));
    end if;
    if r.seller_user_id is not null then
      perform public.dori_pass_record_event(r.seller_user_id,'stock_trade',r.id::text || ':seller',4,r.executed_at,jsonb_build_object('stock_id',r.stock_id,'side','sell','notional',r.notional));
    end if;
  end loop;

  for r in select t.id,t.account_number,t.tx_type,t.direction,t.amount,t.created_at,a.auth_user_id
    from public.dori_bank_transactions t join public.dori_bank_accounts a on a.account_number=t.account_number and a.status='active'
    where timezone('Asia/Seoul',t.created_at)::date >= date_trunc('month',timezone('Asia/Seoul',now()))::date and t.created_at <= now()
    order by t.created_at,t.id
  loop
    if r.auth_user_id is not null then
      perform public.dori_pass_record_event(r.auth_user_id,'bank_transaction',r.id::text,2,r.created_at,jsonb_build_object('tx_type',r.tx_type,'direction',r.direction,'amount',r.amount));
    end if;
  end loop;
end
