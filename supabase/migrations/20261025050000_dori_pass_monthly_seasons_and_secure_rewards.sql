CREATE OR REPLACE FUNCTION public.dori_pass_claim_achievement(p_achievement_key text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_uid uuid := auth.uid();
  v_season text := to_char(timezone('Asia/Seoul', now())::date, 'YYYY-MM');
  v_xp integer;
  v_tier integer;
  v_progress integer;
  v_target integer;
  v_reward bigint;
  v_domain_count integer;
  v_weekly_count integer;
begin
  if v_uid is null then raise exception '로그인이 필요합니다.'; end if;
  select coalesce(sum(xp),0)::integer into v_xp from public.dori_pass_event_ledger where user_id=v_uid and season_key=v_season;
  v_tier := least(100,floor(v_xp::numeric/100)::integer);
  select count(*)::integer into v_weekly_count from public.dori_pass_challenge_claims where user_id=v_uid and season_key=v_season;
  select count(distinct event_type)::integer into v_domain_count
  from public.dori_pass_event_ledger
  where user_id=v_uid and season_key=v_season
    and event_type in ('daily_mission','attendance','random_box','chess_game','study_focus','stock_trade','bank_transaction','news_read');

  case p_achievement_key
    when 'first_100' then v_progress:=v_xp; v_target:=100; v_reward:=5000;
    when 'tier_25' then v_progress:=v_tier; v_target:=25; v_reward:=10000;
    when 'tier_50' then v_progress:=v_tier; v_target:=50; v_reward:=25000;
    when 'tier_100' then v_progress:=v_tier; v_target:=100; v_reward:=100000;
    when 'weekly_hero' then v_progress:=v_weekly_count; v_target:=8; v_reward:=20000;
    when 'multi_domain' then v_progress:=v_domain_count; v_target:=4; v_reward:=15000;
    else return jsonb_build_object('ok',false,'reason','unknown_achievement');
  end case;
  if v_progress < v_target then return jsonb_build_object('ok',false,'reason','not_completed','progress',v_progress,'target',v_target); end if;
  if exists(select 1 from public.dori_pass_achievement_claims where user_id=v_uid and season_key=v_season and achievement_key=p_achievement_key) then
    return jsonb_build_object('ok',false,'reason','already_claimed');
  end if;

  insert into public.dori_pass_achievement_claims(user_id,season_key,achievement_key,coin_reward)
  values(v_uid,v_season,p_achievement_key,v_reward);
  update public.users set doldolcoin=coalesce(doldolcoin,0)+v_reward where user_id=v_uid::text;
  if not found then raise exception '사용자 계정 정보를 찾을 수 없습니다.'; end if;
  return jsonb_build_object('ok',true,'achievement_key',p_achievement_key,'coins',v_reward);
end
$function$;

CREATE OR REPLACE FUNCTION public.dori_pass_claim_all_available()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_uid uuid := auth.uid();
  v_season text := to_char(timezone('Asia/Seoul', now())::date, 'YYYY-MM');
  v_xp integer;
  v_unlocked integer;
  v_tier integer;
  v_result jsonb;
  v_count integer := 0;
  v_coins bigint := 0;
begin
  if v_uid is null then raise exception '로그인이 필요합니다.'; end if;
  select coalesce(sum(xp),0)::integer into v_xp
  from public.dori_pass_event_ledger where user_id=v_uid and season_key=v_season;
  v_unlocked := least(100,floor(v_xp::numeric/100)::integer);
  for v_tier in 1..v_unlocked loop
    v_result := public.dori_pass_claim_tier(v_tier);
    if coalesce((v_result->>'ok')::boolean,false) then
      v_count := v_count + 1;
      v_coins := v_coins + coalesce((v_result->>'coins')::bigint,0);
    end if;
  end loop;
  return jsonb_build_object('ok',true,'claimed_count',v_count,'coins',v_coins,'xp',v_xp,'tier',v_unlocked);
end
$function$;

CREATE OR REPLACE FUNCTION public.dori_pass_claim_challenge(p_challenge_key text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_uid uuid := auth.uid();
  v_today date := timezone('Asia/Seoul', now())::date;
  v_season text := to_char(timezone('Asia/Seoul', now())::date, 'YYYY-MM');
  v_week_start date := date_trunc('week', timezone('Asia/Seoul', now()))::date;
  v_event_type text;
  v_target integer;
  v_xp integer;
  v_progress integer;
begin
  if v_uid is null then raise exception '로그인이 필요합니다.'; end if;
  select d.event_type, d.target_count, d.xp_reward
    into v_event_type, v_target, v_xp
  from (values
    ('show_up', 'attendance', 5, 200),
    ('lucky_drop', 'random_box', 4, 180),
    ('focus_routine', 'study_focus', 3, 250),
    ('chess_strategist', 'chess_game', 3, 200),
    ('market_maker', 'stock_trade', 3, 180),
    ('daily_goals', 'daily_mission', 8, 250)
  ) d(challenge_key,event_type,target_count,xp_reward)
  where d.challenge_key = p_challenge_key;

  if v_event_type is null then return jsonb_build_object('ok',false,'reason','unknown_challenge'); end if;
  perform pg_advisory_xact_lock(hashtextextended(v_uid::text || '|challenge|' || v_season || '|' || v_week_start::text,0));
  if exists(select 1 from public.dori_pass_challenge_claims where user_id=v_uid and season_key=v_season and week_start=v_week_start and challenge_key=p_challenge_key) then
    return jsonb_build_object('ok',false,'reason','already_claimed');
  end if;

  select count(*)::integer into v_progress
  from public.dori_pass_event_ledger
  where user_id=v_uid and season_key=v_season and event_type=v_event_type
    and event_date between v_week_start and v_today;
  if v_progress < v_target then
    return jsonb_build_object('ok',false,'reason','not_completed','progress',least(v_progress,v_target),'target',v_target);
  end if;

  insert into public.dori_pass_challenge_claims(user_id,season_key,week_start,challenge_key,xp_reward)
  values(v_uid,v_season,v_week_start,p_challenge_key,v_xp);

  perform public.dori_pass_record_event(
    v_uid, 'weekly_challenge', v_week_start::text || ':' || p_challenge_key, v_xp, now(),
    jsonb_build_object('challenge_key',p_challenge_key,'week_start',v_week_start)
  );
  return jsonb_build_object('ok',true,'challenge_key',p_challenge_key,'xp_reward',v_xp,'progress',v_progress,'target',v_target);
end
$function$;

CREATE OR REPLACE FUNCTION public.dori_pass_claim_tier(p_tier integer)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_uid uuid := auth.uid();
  v_season text := to_char(timezone('Asia/Seoul', now())::date, 'YYYY-MM');
  v_xp integer;
  v_reward jsonb;
  v_cosmetic jsonb;
  v_coins bigint;
begin
  if v_uid is null then raise exception '로그인이 필요합니다.'; end if;
  if p_tier is null or p_tier < 1 or p_tier > 100 then return jsonb_build_object('ok',false,'reason','invalid_tier'); end if;
  perform pg_advisory_xact_lock(hashtextextended(v_uid::text || '|pass|' || v_season, 0));
  select coalesce(sum(xp),0)::integer into v_xp
  from public.dori_pass_event_ledger where user_id=v_uid and season_key=v_season;
  if floor(v_xp::numeric / 100)::integer < p_tier then return jsonb_build_object('ok',false,'reason','not_unlocked','xp',v_xp,'tier',p_tier); end if;
  if exists(select 1 from public.dori_pass_tier_claims where user_id=v_uid and season_key=v_season and tier=p_tier) then
    return jsonb_build_object('ok',false,'reason','already_claimed','tier',p_tier);
  end if;

  v_reward := public.dori_pass_tier_reward(v_season, p_tier);
  v_coins := (v_reward->>'coins')::bigint;

  insert into public.dori_pass_tier_claims(user_id,season_key,tier,coin_reward)
  values(v_uid,v_season,p_tier,v_coins);

  update public.users set doldolcoin = coalesce(doldolcoin,0) + v_coins
  where user_id = v_uid::text;
  if not found then raise exception '사용자 계정 정보를 찾을 수 없습니다.'; end if;

  for v_cosmetic in select value from jsonb_array_elements(coalesce(v_reward->'cosmetics','[]'::jsonb)) as x(value)
  loop
    insert into public.dori_pass_cosmetics
      (user_id,season_key,tier,cosmetic_key,kind,display_name,rarity,icon)
    values
      (v_uid,v_season,p_tier,v_cosmetic->>'key',v_cosmetic->>'kind',v_cosmetic->>'name',
       v_cosmetic->>'rarity',coalesce(v_cosmetic->>'icon','✦'))
    on conflict (user_id,cosmetic_key) do nothing;
  end loop;

  return jsonb_build_object('ok',true,'tier',p_tier,'coins',v_coins,'cosmetics',coalesce(v_reward->'cosmetics','[]'::jsonb),'xp',v_xp);
end
$function$;

